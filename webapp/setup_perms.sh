#!/bin/bash

# 1. Создаем системного пользователя без пароля и домашней папки (так безопаснее)
sudo useradd -r -s /bin/false webapp_user

# 2. Меняем владельца папки и всех вложенных файлов на этого пользователя
sudo chown -R webapp_user:webapp_user webapp/

# 3. Выдаем права: владельцу (7: чтение/запись/запуск), группе (5: чтение/запуск), остальным (0: ничего)
sudo chmod -R 750 webapp/

echo "Права успешно настроены!"
